# ---------------------------------------------------------------------------
# Dataset Loading
# ---------------------------------------------------------------------------

def load_dataset(path: str | Path) -> list[dict[str, Any]]:
    """Load mathematical problems dataset from a JSON file.

    Args:
        path: Path to the dataset JSON file.

    Returns:
        List of problem definition dictionaries.

    Raises:
        FileNotFoundError: If the specified file does not exist.
        json.JSONDecodeError: If the dataset file is not valid JSON.
    """
    dataset_path = Path(path)
    if not dataset_path.is_file():
        raise FileNotFoundError(f"Dataset file not found at: {dataset_path.resolve()}")

    with open(dataset_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, list):
        raise ValueError(f"Expected JSON list in dataset, got {type(data).__name__}")

    return data


# ---------------------------------------------------------------------------
# Symbolic Comparison for Baseline
# ---------------------------------------------------------------------------

def evaluate_baseline_symbolic_match(
    answer: str,
    expected_code: Optional[str],
    pipeline: MathPipeline,
) -> bool:
    """Evaluate whether a baseline text answer matches the expected answer symbolically.

    Args:
        answer: Text answer generated by pure LLM baseline.
        expected_code: Ground truth Python/SymPy code defining the expected answer.
        pipeline: MathPipeline instance used for expression evaluation and verification.

    Returns:
        True if the answer is symbolically equivalent to the expected result, False otherwise.
    """
    if not answer or not expected_code:
        return False

    clean_answer = answer.strip()
    if not clean_answer:
        return False

    # Obtain expected SymPy object from ground truth code
    try:
        expected_obj = pipeline._evaluate_expected_answer(expected_code)
    except Exception as exc:
        logger.debug("Failed to evaluate expected answer code: %s", exc)
        return False

    # 1. Handle markdown python code block (e.g. in mock mode or code outputs)
    if "```" in clean_answer:
        try:
            extracted_code = pipeline._extract_code(clean_answer)
            exec_res, _ = pipeline._execute_code(extracted_code)
            return pipeline._check_symbolic_equivalence(exec_res, expected_obj)
        except Exception:
            return False

    # 2. Candidate strings to evaluate (boxed content, full text)
    candidates: list[str] = []

    # Extract \boxed{...} if present
    boxed_match = re.search(r"\\boxed\{([^}]+)\}", clean_answer)
    if boxed_match:
        candidates.append(boxed_match.group(1).strip())

    candidates.append(clean_answer)

    # 3. Test candidates for mathematical equivalence
    for candidate in candidates:
        norm_str = candidate.replace("$", "").replace("\\left", "").replace("\\right", "").strip()
        if not norm_str or norm_str.startswith(("print(", "import ", "def ", "class ")):
            continue
        try:
            cand_sym = sympify(norm_str)
            if pipeline._check_symbolic_equivalence(cand_sym, expected_obj):
                return True
        except Exception:
            pass

    return False


# ---------------------------------------------------------------------------
# Benchmark Execution per Mode
# ---------------------------------------------------------------------------

def run_mode(
    pipeline: MathPipeline,
    dataset: list[dict[str, Any]],
    mode: str,
    delay: float = 0.0,
) -> list[dict[str, Any]]:
    """Run a specific solving mode ('hybrid' or 'baseline') across the dataset.

    Args:
        pipeline: Initialized MathPipeline instance.
        dataset: List of problem dictionaries to evaluate.
        mode: Either 'hybrid' or 'baseline'.

    Returns:
        List of detailed per-problem evaluation results.
    """
    per_problem: list[dict[str, Any]] = []
    total = len(dataset)

    for idx, item in enumerate(dataset, start=1):
        problem_id = str(item.get("id", f"problem_{idx}"))
        problem_text = str(item.get("problem", ""))
        expected_code = item.get("expected_answer_code")
        task_type = str(item.get("task_type", "general"))
        category = str(item.get("category", "unknown"))
        difficulty = str(item.get("difficulty", "unknown"))

        print(f"  [{idx:>2}/{total}] {problem_id:<20}", end=" ", flush=True)

        start_time = time.perf_counter()

        if mode == "hybrid":
            task_res: TaskResult = pipeline.solve_hybrid(
                problem=problem_text,
                expected_answer_code=expected_code if expected_code else None,
                task_type=task_type,
            )
            elapsed = time.perf_counter() - start_time

            success = bool(task_res.success)
            exec_rate = 1.0 if task_res.execution_rate else 0.0
            sym_match = 1.0 if task_res.symbolic_match else 0.0
            attempts = max(1, task_res.attempts)
            pass_1 = 1.0 if (success and attempts == 1) else 0.0
            pass_3 = 1.0 if (success and attempts <= 3) else 0.0
            answer_str = task_res.answer or ""
            error_str = task_res.error or ""

        elif mode == "baseline":
            task_res = pipeline.solve_baseline(problem=problem_text)
            elapsed = time.perf_counter() - start_time

            answer_str = task_res.answer or ""
            error_str = task_res.error or ""
            attempts = 1

            # Baseline has no code execution in isolated SymPy environment
            exec_rate = 0.0

            # Evaluate symbolic match against expected code if available
            if expected_code:
                is_match = evaluate_baseline_symbolic_match(
                    answer=answer_str,
                    expected_code=expected_code,
                    pipeline=pipeline,
                )
                sym_match = 1.0 if is_match else 0.0
                success = is_match
            else:
                sym_match = 0.0
                success = bool(answer_str.strip())

            pass_1 = 1.0 if success else 0.0
            pass_3 = 1.0 if success else 0.0

        else:
            raise ValueError(f"Unsupported benchmark mode: {mode}")

        status_marker = "✓" if success else "✗"
        print(f"{status_marker}  ({elapsed:.2f}s)")

        per_problem.append({
            "id": problem_id,
            "category": category,
            "task_type": task_type,
            "difficulty": difficulty,
            "mode": mode,
            "success": success,
            "execution_rate": exec_rate,
            "symbolic_match": sym_match,
            "pass_at_1": pass_1,
            "pass_at_3": pass_3,
            "attempts": attempts,
            "answer": answer_str[:300],
            "error": error_str[:300],
            "elapsed_seconds": round(elapsed, 4),
        })

        if delay > 0 and idx < total:
            time.sleep(delay)

    return per_problem


# ---------------------------------------------------------------------------
# Metrics Computation
# ---------------------------------------------------------------------------

def compute_metrics(results: list[dict[str, Any]]) -> dict[str, Any]:
    """Compute aggregate benchmark metrics and per-category breakdown.

    Metrics include:
    - execution_rate: Fraction of problems where code ran without error (hybrid only).
    - symbolic_equivalence_rate: Fraction where answer matches expected answer.
    - pass_at_1: Success on first attempt without retries.
    - pass_at_3: Success within 3 attempts.
    - category_breakdown: Per-category statistics.

    Args:
        results: List of per-problem result dictionaries.

    Returns:
        Dictionary containing overall and per-category aggregated metrics.
    """
    total = len(results)
    if total == 0:
        return {}

    mode = results[0].get("mode", "unknown")
    is_hybrid = (mode == "hybrid")

    exec_successes = sum(1 for r in results if r.get("execution_rate", 0.0) == 1.0)
    symbolic_matches = sum(1 for r in results if r.get("symbolic_match", 0.0) == 1.0)
    pass_at_1_successes = sum(1 for r in results if r.get("pass_at_1", 0.0) == 1.0)
    pass_at_3_successes = sum(1 for r in results if r.get("pass_at_3", 0.0) == 1.0)
    total_successes = sum(1 for r in results if r.get("success") is True or r.get("success") == 1.0)

    total_attempts = sum(r.get("attempts", 1) for r in results)
    total_elapsed = sum(r.get("elapsed_seconds", 0.0) for r in results)

    # Category breakdown calculation
    categories: dict[str, list[dict[str, Any]]] = {}
    for r in results:
        cat = str(r.get("category", "unknown"))
        categories.setdefault(cat, []).append(r)

    category_breakdown: dict[str, dict[str, Any]] = {}
    for cat, cat_items in sorted(categories.items()):
        cn = len(cat_items)
        c_succ = sum(1 for r in cat_items if r.get("success") is True or r.get("success") == 1.0)
        c_sym = sum(1 for r in cat_items if r.get("symbolic_match", 0.0) == 1.0)
        c_p1 = sum(1 for r in cat_items if r.get("pass_at_1", 0.0) == 1.0)
        c_p3 = sum(1 for r in cat_items if r.get("pass_at_3", 0.0) == 1.0)

        cat_stat: dict[str, Any] = {
            "total": cn,
            "success": c_succ,
            "success_rate": round(c_succ / cn, 4),
            "symbolic_equivalence_rate": round(c_sym / cn, 4),
            "pass_at_1": round(c_p1 / cn, 4),
            "pass_at_3": round(c_p3 / cn, 4),
        }
        if is_hybrid:
            c_exec = sum(1 for r in cat_items if r.get("execution_rate", 0.0) == 1.0)
            cat_stat["execution_rate"] = round(c_exec / cn, 4)
        else:
            cat_stat["execution_rate"] = "N/A"

        category_breakdown[cat] = cat_stat

    metrics: dict[str, Any] = {
        "mode": mode,
        "total_problems": total,
        "execution_rate": round(exec_successes / total, 4) if is_hybrid else "N/A",
        "symbolic_equivalence_rate": round(symbolic_matches / total, 4),
        "pass_at_1": round(pass_at_1_successes / total, 4),
        "pass_at_3": round(pass_at_3_successes / total, 4),
        "success_rate": round(total_successes / total, 4),
        "avg_attempts": round(total_attempts / total, 2) if is_hybrid else 1.0,
        "avg_elapsed_seconds": round(total_elapsed / total, 4),
        "category_breakdown": category_breakdown,
    }

    return metrics


# ---------------------------------------------------------------------------
# ASCII Report Presentation
# ---------------------------------------------------------------------------

def print_report(
    hybrid_metrics: Optional[dict[str, Any]],
    baseline_metrics: Optional[dict[str, Any]],
) -> None:
    """Print an ASCII table comparison report to the console.

    Args:
        hybrid_metrics: Aggregate metrics dictionary for hybrid mode.
        baseline_metrics: Aggregate metrics dictionary for baseline mode.
    """
    sep = "=" * 70
    print(f"\n{sep}")
    print("  BENCHMARK REPORT — Hybrid (LLM + SymPy) vs Baseline (Pure LLM)")
    print(sep)

    col_w = [38, 14, 14]
    header = f"  {'Metric':<{col_w[0]}} {'Hybrid':>{col_w[1]}} {'Baseline':>{col_w[2]}}"
    print(header)
    print("  " + "-" * (sum(col_w) + 2))

    hm = hybrid_metrics or {}
    bm = baseline_metrics or {}

    def format_val(val: Any) -> str:
        if val is None or val == "":
            return "—"
        if isinstance(val, float):
            return f"{val:.4f}"
        return str(val)

    rows: list[tuple[str, Any, Any]] = [
        ("Total Problems", hm.get("total_problems"), bm.get("total_problems")),
        ("Execution Rate (code executed)", hm.get("execution_rate"), bm.get("execution_rate")),
        ("Symbolic Equivalence Rate", hm.get("symbolic_equivalence_rate"), bm.get("symbolic_equivalence_rate")),
        ("Pass@1 (success on 1st attempt)", hm.get("pass_at_1"), bm.get("pass_at_1")),
        ("Pass@3 (success within 3 attempts)", hm.get("pass_at_3"), bm.get("pass_at_3")),
        ("Success Rate (overall)", hm.get("success_rate"), bm.get("success_rate")),
        ("Average Attempts", hm.get("avg_attempts"), bm.get("avg_attempts")),
        ("Average Elapsed Time (s)", hm.get("avg_elapsed_seconds"), bm.get("avg_elapsed_seconds")),
    ]

    for label, h_val, b_val in rows:
        print(f"  {label:<{col_w[0]}} {format_val(h_val):>{col_w[1]}} {format_val(b_val):>{col_w[2]}}")

    print(sep)

    # Display per-category breakdown
    categories: set[str] = set()
    if hm.get("category_breakdown"):
        categories.update(hm["category_breakdown"].keys())
    if bm.get("category_breakdown"):
        categories.update(bm["category_breakdown"].keys())

    if categories:
        print("\n  Per-Category Breakdown:")
        cat_sep = "-" * 70
        print("  " + cat_sep)
        print(f"  {'Category':<16} {'Mode':<10} {'Total':>6} {'Pass@1':>9} {'Pass@3':>9} {'Success%':>9}")
        print("  " + cat_sep)

        for cat in sorted(categories):
            if hm.get("category_breakdown", {}).get(cat):
                cstats = hm["category_breakdown"][cat]
                p1_s = f"{cstats.get('pass_at_1', 0.0):.4f}"
                p3_s = f"{cstats.get('pass_at_3', 0.0):.4f}"
                sr_s = f"{cstats.get('success_rate', 0.0):.4f}"
                print(f"  {cat:<16} {'Hybrid':<10} {cstats.get('total', 0):>6} {p1_s:>9} {p3_s:>9} {sr_s:>9}")
            if bm.get("category_breakdown", {}).get(cat):
                cstats = bm["category_breakdown"][cat]
                p1_s = f"{cstats.get('pass_at_1', 0.0):.4f}"
                p3_s = f"{cstats.get('pass_at_3', 0.0):.4f}"
                sr_s = f"{cstats.get('success_rate', 0.0):.4f}"
                print(f"  {cat:<16} {'Baseline':<10} {cstats.get('total', 0):>6} {p1_s:>9} {p3_s:>9} {sr_s:>9}")
        print("  " + cat_sep)

    print()


# ---------------------------------------------------------------------------
# JSON Report Persistence
# ---------------------------------------------------------------------------

def save_report(
    output_path: str | Path,
    hybrid_results: Optional[list[dict[str, Any]]],
    baseline_results: Optional[list[dict[str, Any]]],
    hybrid_metrics: Optional[dict[str, Any]],
    baseline_metrics: Optional[dict[str, Any]],
    config: dict[str, Any],
) -> None:
    """Save detailed JSON report to disk, creating parent directories if needed.

    Args:
        output_path: File path where the JSON report will be stored.
        hybrid_results: List of per-problem results for hybrid mode.
        baseline_results: List of per-problem results for baseline mode.
        hybrid_metrics: Computed aggregate metrics for hybrid mode.
        baseline_metrics: Computed aggregate metrics for baseline mode.
        config: Configuration dictionary with run parameters.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    report_payload: dict[str, Any] = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "config": config,
        "per_problem_results": {
            "hybrid": hybrid_results if hybrid_results is not None else [],
            "baseline": baseline_results if baseline_results is not None else [],
        },
        "aggregate_metrics": {
            "hybrid": hybrid_metrics,
            "baseline": baseline_metrics,
        },
    }

    with open(path, "w", encoding="utf-8") as f:
        json.dump(report_payload, f, ensure_ascii=False, indent=2)

    print(f"  → JSON report successfully saved to: {path.resolve()}")


# ---------------------------------------------------------------------------
# CLI Argument Parser & Entry Point
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    """Parse command line arguments for the benchmark script.

    Returns:
        Parsed argparse.Namespace containing CLI flags.
    """
    parser = argparse.ArgumentParser(
        description="Benchmark comparing Pure LLM baseline vs Hybrid LLM+SymPy solver system."
    )
    parser.add_argument(
        "--mode",
        choices=["hybrid", "baseline", "both"],
        default="both",
        help="Evaluation mode to run: 'hybrid', 'baseline', or 'both' (default: both).",
    )
    parser.add_argument(
        "--dataset",
        type=str,
        default="data/calculus_dataset.json",
        help="Path to the calculus problems JSON dataset (default: data/calculus_dataset.json).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="results/benchmark_report.json",
        help="Path for writing the output JSON report (default: results/benchmark_report.json).",
    )
    parser.add_argument(
        "--max-problems",
        type=int,
        default=None,
        help="Maximum number of problems to evaluate (for testing or fast runs).",
    )
    parser.add_argument(
        "--delay",
        type=float,
        default=1.5,
        help="Delay in seconds between requests to prevent rate limiting (default: 1.5).",
    )
    return parser.parse_args()


def main() -> None:
    """Main execution function for running the benchmark."""
    args = parse_args()

    mock_mode_env = os.getenv("MOCK_MODE", "false").strip().lower()
    is_mock = mock_mode_env in ("true", "1", "yes", "t", "on")
    model_name = os.getenv("LLM_MODEL", "unknown")
    max_retries = int(os.getenv("MAX_RETRIES", "3"))

    print(f"\n{'='*70}")
    print("  Neuro-Symbolic AI — Mathematical Benchmark")
    print(f"  Mode: {args.mode.upper()}  |  MOCK_MODE={is_mock}  |  Model: {model_name}")
    print(f"  Dataset: {args.dataset}")
    print(f"{'='*70}\n")

    # Load problem dataset
    try:
        dataset = load_dataset(args.dataset)
    except FileNotFoundError as err:
        print(f"ERROR: {err}")
        sys.exit(1)
    except Exception as exc:
        print(f"ERROR: Failed to load dataset: {exc}")
        sys.exit(1)

    # Optional problem count truncation
    if args.max_problems is not None and args.max_problems > 0:
        dataset = dataset[: args.max_problems]
        print(f"  → Truncated evaluation to {len(dataset)} problem(s) (--max-problems)\n")

    config_info: dict[str, Any] = {
        "mode": args.mode,
        "dataset": str(args.dataset),
        "output": str(args.output),
        "max_problems": args.max_problems,
        "mock_mode": is_mock,
        "llm_model": model_name,
        "max_retries": max_retries,
    }

    pipeline_cfg = PipelineConfig(
        max_retries=max_retries,
        mock_mode=is_mock,
    )
    pipeline = MathPipeline(config=pipeline_cfg)

    hybrid_results: Optional[list[dict[str, Any]]] = None
    baseline_results: Optional[list[dict[str, Any]]] = None
    hybrid_metrics: Optional[dict[str, Any]] = None
    baseline_metrics: Optional[dict[str, Any]] = None

    # Run Hybrid evaluation
    if args.mode in ("hybrid", "both"):
        print("▶ Running Hybrid mode (LLM + SymPy):")
        hybrid_results = run_mode(pipeline, dataset, "hybrid", delay=args.delay)
        hybrid_metrics = compute_metrics(hybrid_results)

    # Run Baseline evaluation
    if args.mode in ("baseline", "both"):
        print("\n▶ Running Baseline mode (Pure LLM):")
        baseline_results = run_mode(pipeline, dataset, "baseline", delay=args.delay)
        baseline_metrics = compute_metrics(baseline_results)

    # Display console ASCII report
    print_report(hybrid_metrics, baseline_metrics)

    # Save detailed JSON report
    save_report(
        output_path=args.output,
        hybrid_results=hybrid_results,
        baseline_results=baseline_results,
        hybrid_metrics=hybrid_metrics,
        baseline_metrics=baseline_metrics,
        config=config_info,
    )


if __name__ == "__main__":
    main()
