"""benchmark.py — Benchmark script for comparing Pure LLM baseline vs Hybrid LLM+SymPy system.

This module evaluates and compares two mathematical reasoning approaches:
1. Hybrid System: LLM semantic translation into SymPy code with AST safety validation,
   isolated sandboxed execution, backward verification, and iterative self-correction.
2. Baseline System: Pure LLM direct natural language / LaTeX text generation.

Key Metrics Computed:
- execution_rate: Fraction of problems where generated SymPy code executed without errors (hybrid only).
- symbolic_equivalence_rate: Fraction where candidate answer matches ground truth symbolically via SymPy.
- pass_at_1: Fraction of problems solved successfully on the very first attempt (no retries needed).
- pass_at_3: Fraction of problems solved successfully within 3 attempts.
- category_breakdown: Granular per-category evaluation metrics.

Usage Examples:
    # Run in mock mode (no API keys required):
    $env:MOCK_MODE="true"; python benchmark.py

    # Run both modes on the full dataset:
    python benchmark.py --mode both

    # Run hybrid mode only on first 5 problems:
    python benchmark.py --mode hybrid --max-problems 5 --output results/custom_report.json
"""

